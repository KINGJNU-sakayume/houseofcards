import { expect, test } from '@playwright/test';
import { createFoundedGame } from '../helpers';
import { dispatchCommand } from '../../src/engine/simulation/engine';
import { stateHash } from '../../src/engine/simulation/determinism';

test('C1 founding gate, actual costs, research, stale survey, honest stubs and mobile layout', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('./#/election');
  await expect(page.getByRole('heading', { name: '새로운 정당의 첫 페이지' })).toBeVisible();
  await expect(page.getByRole('button', { name: '다음 주로' })).toBeDisabled();
  await expect(page.getByText('법적 창당 절차', { exact: false })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByLabel('정당 이름', { exact: true }).fill('내일의 정당');
  await page.getByLabel('약칭', { exact: true }).fill('내일');
  for (const value of ['주거개혁', '사회안전망', '과학기술']) await page.getByRole('checkbox', { name: value, exact: false }).check();
  await page.getByRole('button', { name: '정당 창당', exact: true }).click();
  await expect(page.getByRole('heading', { name: '이 세이브의 선거제도' })).toBeVisible();
  await expect(page.getByTestId('allocation-example')).toContainText('선거 결과나 예측이 아니며');
  await page.getByRole('link', { name: '정책', exact: false }).click();
  await expect(page.getByText('공표 비용: 실무 인력 1 · 의제 슬롯 1').first()).toBeVisible();
  await page.getByRole('radio', { name: '임대지원 확대 4단계' }).click();
  await expect(page.getByRole('radio', { name: '임대지원 확대 4단계' })).toBeChecked();
  await expect(page.getByRole('button', { name: '다음 주로' })).toBeEnabled();
  await page.getByRole('button', { name: '임대지원 확대 공표' }).click();
  await expect(page.getByTestId('published-housing.rent-support')).toContainText('공표 4');
  await page.getByRole('link', { name: '데이터 허브', exact: false }).click();
  await expect(page.getByTestId('survey-gate')).toBeVisible();
  await page.getByRole('button', { name: '내부조사 의뢰', exact: true }).click();
  await expect(page.getByTestId('current-support')).toBeVisible();
  const snapshot = await page.getByTestId('current-support').textContent();
  await page.getByRole('link', { name: '우리 정당', exact: false }).click();
  await page.getByRole('button', { name: '주택 연구', exact: true }).click();
  await expect(page.getByText('완료 예정 2026-11-16')).toBeVisible();
  await expect(page.getByRole('button', { name: '의료 연구', exact: true })).toBeDisabled();
  await expect(page.getByText('실무 인력이 부족합니다', { exact: false }).first()).toBeVisible();
  await page.getByLabel('직원 수준', { exact: false }).selectOption('1');
  await expect(page.getByRole('button', { name: '다음 주로' })).toBeEnabled();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'work/c1-party-mobile.png', fullPage: true });
  for (let i = 0; i < 4; i++) { await page.getByRole('button', { name: '다음 주로' }).click(); await expect(page.getByRole('button', { name: '다음 주로' })).toBeEnabled(); }
  await expect(page.getByText('완료 예정 2026-11-16')).toHaveCount(0);
  await page.getByRole('link', { name: '데이터 허브', exact: false }).click();
  await expect(page.getByTestId('current-support')).toHaveText(snapshot!);
  await expect(page.getByTestId('survey-date')).toContainText('4주 경과');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.reload(); await expect(page.getByTestId('current-support')).toHaveText(snapshot!);
  let expected = createFoundedGame(20261019);
  for (const command of [{ type: 'SET_PLATFORM_DRAFT', leverId: 'housing.rent-support', value: 4 }, { type: 'PUBLISH_PLATFORM', leverId: 'housing.rent-support' }, { type: 'COMMISSION_INTERNAL_SURVEY' }, { type: 'START_POLICY_RESEARCH', domain: 'housing' }, { type: 'SET_STAFF_LEVEL', level: 1 }] as const) expected = dispatchCommand(expected, command);
  for (let i = 0; i < 4; i++) expected = dispatchCommand(expected, { type: 'ADVANCE_WEEK' });
  await page.getByRole('button', { name: '저장 / 불러오기' }).click(); await page.getByText('저장 무결성 정보').click();
  await expect(page.getByTestId('state-hash')).toHaveText(stateHash(expected));
  expect(errors).toEqual([]);
});
